import { readFile, writeFile } from "node:fs/promises";
import { pathToFileURL } from "node:url";

const artifactUrl = new URL("../artifacts/contracts/CertificateRegistry.sol/CertificateRegistry.json", import.meta.url);
const configUrl = new URL("../../frontend/src/config/", import.meta.url);

export function deploymentFile(chainId) {
  if (chainId === 31337) return new URL("deployment.local.json", configUrl);
  if (chainId === 11155111) return new URL("deployment.sepolia.json", configUrl);
  throw new Error(`Unsupported deployment chain ${chainId}.`);
}

export async function writeAbi() {
  const { abi } = JSON.parse(await readFile(artifactUrl, "utf8"));
  await writeFile(
    new URL("certificateAbi.ts", configUrl),
    "// Generated by npm --prefix contracts run export:abi.\nexport const registryAbi = " +
      JSON.stringify(abi, null, 2) + " as const;\n",
  );
}

export async function writeDeployment(deployment) {
  await writeFile(deploymentFile(deployment.chainId), JSON.stringify(deployment, null, 2) + "\n");
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) await writeAbi();
